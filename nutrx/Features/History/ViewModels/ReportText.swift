import Foundation

/// The report's words (docs/pro/design/7-doctor-report): plain and clinical, readable by a doctor in 30 seconds.
struct ReportText {
    let report: DoctorReport
    var calendar: Calendar = .current
    var locale: Locale = .current

    static let title = "Intake report"
    static let disclaimer = "Self-reported intake, logged by the patient in nutrx. Amounts and goals were set by the user."
    static let healthHeader = "With Apple Health · last 28 days"
    static let summaryTitle = "Summary by nutrient"

    /// Under a section's chart, in the words of its goal.
    static func chartCaption(_ goalType: GoalType, hasUpperBound: Bool) -> String {
        switch goalType {
        case .maximum: "Daily totals. Dark bars stayed within the limit; light bars went over. Dashed line: limit."
        case .range where hasUpperBound: "Daily totals. Dark bars were in range; light bars weren't. Dashed lines: range."
        default: "Daily totals. Dark bars met the goal; light bars didn't. Dashed line: goal."
        }
    }

    /// "16 July – 13 October 2026 · 90 days".
    var period: String {
        let days = report.dayCount == 1 ? "1 day" : "\(report.dayCount) days"
        return "\(dates) · \(days)"
    }

    /// "16 July – 13 October 2026" (the year once when both ends share it).
    var dates: String {
        let sameYear = calendar.component(.year, from: report.start) == calendar.component(.year, from: report.end)
        let startText = report.start.formatted(.dateTime.day().month(.wide).year(sameYear ? .omitted : .defaultDigits)
            .locale(locale))
        let endText = report.end.formatted(.dateTime.day().month(.wide).year().locale(locale))
        return "\(startText) – \(endText)"
    }

    var daysWithEntries: String { "\(report.daysWithEntries) of \(report.dayCount)" }

    /// "81%", or "—" with nothing to count.
    func percent(_ rate: Double?) -> String {
        rate.map { "\(Int(($0 * 100).rounded()))%" } ?? "—"
    }

    /// A weekly section's box (#132): "3 of 4", or "—" without a whole week in the period.
    func weeksMet(_ weeks: AnalyticsWeeks) -> String {
        weeks.total > 0 ? "\(weeks.met) of \(weeks.total)" : "—"
    }

    /// The summary table's rate: "81%", or for a weekly section "3 of 4 weeks", so it isn't read as days (#248).
    func summaryRate(_ section: DoctorReport.Section) -> String {
        guard let weeks = section.weeks else { return percent(section.hitRate) }
        return weeks.total > 0 ? "\(weeksMet(weeks)) weeks" : "—"
    }

    var longestStreak: String { report.longestStreak == 1 ? "1 day" : "\(report.longestStreak) days" }

    /// "At least 4,000 IU", "At most 400 mg", "Between 120–160 g"; a weekly one adds ", 3 times a week" (#248).
    func goal(_ section: DoctorReport.Section) -> String {
        let goal = switch section.goalType {
        case .minimum: "At least \(amount(section.target, section.unit))"
        case .maximum: "At most \(amount(section.target, section.unit))"
        case .range:
            if let upper = section.upperBound {
                "Between \(number(section.target))–\(number(upper)) \(section.unit)"
            } else {
                "At least \(amount(section.target, section.unit))"
            }
        }
        guard let times = section.weeklyTimes else { return goal }
        return goal + (times == 1 ? ", once a week" : ", \(times) times a week")
    }

    func average(_ section: DoctorReport.Section) -> String {
        section.average.map { amount($0, section.unit) } ?? "—"
    }

    /// "Goal: at least 4,000 IU", beside a section's title.
    func goalLine(_ section: DoctorReport.Section) -> String {
        let text = goal(section)
        return "Goal: " + text.prefix(1).lowercased() + text.dropFirst()
    }

    /// The chart's date labels, by day index: the first and last day ("16 Jul", "13 Oct") and each month's first day
    /// in between ("Aug"), leaving out a month too close to either end to fit beside its label.
    func axisLabels() -> [(index: Int, text: String)] {
        let days = report.days
        guard let first = days.first, let last = days.last else { return [] }
        let dayMonth = Date.FormatStyle.dateTime.day().month(.abbreviated).locale(locale)
        var labels = [(index: 0, text: first.formatted(dayMonth))]
        let clearance = max(3, days.count / 10)
        for (index, day) in days.enumerated() where calendar.component(.day, from: day) == 1 {
            guard index >= clearance, index <= days.count - 1 - clearance else { continue }
            labels.append((index, day.formatted(.dateTime.month(.abbreviated).locale(locale))))
        }
        if days.count > 1 { labels.append((days.count - 1, last.formatted(dayMonth))) }
        return labels
    }

    /// "Generated by nutrx on 14 Oct 2026".
    func generated(on date: Date) -> String {
        "Generated by nutrx on \(date.formatted(.dateTime.day().month(.abbreviated).year().locale(locale)))"
    }

    static func pageNumber(_ page: Int, of count: Int) -> String { "page \(page) of \(count)" }

    /// "2 Aug".
    func noteDate(_ date: Date) -> String { date.formatted(.dateTime.day().month(.abbreviated).locale(locale)) }

    /// "nutrx-report-2026-07-16-to-2026-10-13.pdf".
    var fileName: String {
        let format = Date.ISO8601FormatStyle(timeZone: calendar.timeZone).year().month().day().dateSeparator(.dash)
        return "nutrx-report-\(report.start.formatted(format))-to-\(report.end.formatted(format)).pdf"
    }

    func amount(_ value: Double, _ unit: String) -> String { "\(number(value)) \(unit)" }

    func number(_ value: Double) -> String {
        value.formatted(.number.precision(.fractionLength(0...(value >= 100 ? 0 : 1))).locale(locale))
    }
}

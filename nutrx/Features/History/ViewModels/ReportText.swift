import Foundation

/// The report's words (docs/pro/design/7-doctor-report): plain and clinical, readable by a doctor in 30 seconds.
struct ReportText {
    let report: DoctorReport
    var calendar: Calendar = .current
    var locale: Locale = .current

    static let title = "Intake report"
    static let disclaimer = "Self-reported intake, logged by the patient in nutrx. Amounts and goals were set by the user."
    static let chartCaption = "Daily totals. Dark bars met the goal; light bars didn't. Dashed line: goal."

    /// "16 July – 13 October 2026 · 90 days" (the year once when both ends share it).
    var period: String {
        let sameYear = calendar.component(.year, from: report.start) == calendar.component(.year, from: report.end)
        let startText = report.start.formatted(.dateTime.day().month(.wide).year(sameYear ? .omitted : .defaultDigits)
            .locale(locale))
        let endText = report.end.formatted(.dateTime.day().month(.wide).year().locale(locale))
        let days = report.dayCount == 1 ? "1 day" : "\(report.dayCount) days"
        return "\(startText) – \(endText) · \(days)"
    }

    var daysWithEntries: String { "\(report.daysWithEntries) of \(report.dayCount)" }

    /// "81%", or "—" with nothing to count.
    func percent(_ rate: Double?) -> String {
        rate.map { "\(Int(($0 * 100).rounded()))%" } ?? "—"
    }

    var longestStreak: String { report.longestStreak == 1 ? "1 day" : "\(report.longestStreak) days" }

    /// "At least 4,000 IU", "At most 400 mg", "Between 120–160 g".
    func goal(_ section: DoctorReport.Section) -> String {
        switch section.goalType {
        case .minimum: "At least \(amount(section.target, section.unit))"
        case .maximum: "At most \(amount(section.target, section.unit))"
        case .range:
            if let upper = section.upperBound {
                "Between \(number(section.target))–\(number(upper)) \(section.unit)"
            } else {
                "At least \(amount(section.target, section.unit))"
            }
        }
    }

    func average(_ section: DoctorReport.Section) -> String {
        section.average.map { amount($0, section.unit) } ?? "—"
    }

    /// "Generated by nutrx on 14 Oct 2026".
    func generated(on date: Date) -> String {
        "Generated by nutrx on \(date.formatted(.dateTime.day().month(.abbreviated).year().locale(locale)))"
    }

    static func pageNumber(_ page: Int, of count: Int) -> String { "page \(page) of \(count)" }

    /// "2 Aug".
    func noteDate(_ date: Date) -> String { date.formatted(.dateTime.day().month(.abbreviated).locale(locale)) }

    /// "nutrx-report-2026-07-16-to-2026-10-13.pdf".
    var fileName: String {
        let format = Date.ISO8601FormatStyle(timeZone: calendar.timeZone).year().month().day().dateSeparator(.dash)
        return "nutrx-report-\(report.start.formatted(format))-to-\(report.end.formatted(format)).pdf"
    }

    func amount(_ value: Double, _ unit: String) -> String { "\(number(value)) \(unit)" }

    func number(_ value: Double) -> String {
        value.formatted(.number.precision(.fractionLength(0...(value >= 100 ? 0 : 1))).locale(locale))
    }
}

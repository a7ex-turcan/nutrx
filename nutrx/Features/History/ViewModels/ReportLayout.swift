import CoreGraphics
import Foundation

/// The report's words (docs/pro/design/7-doctor-report): plain and clinical, readable by a doctor in 30 seconds.
struct ReportText {
    let report: DoctorReport
    var calendar: Calendar = .current
    var locale: Locale = .current

    static let title = "Intake report"
    static let disclaimer = "Self-reported intake, logged by the patient in nutrx. Amounts and goals were set by the user."
    static let chartCaption = "Daily totals. Dark bars met the goal; light bars didn't. Dashed line: goal."

    /// "16 July – 13 October 2026 · 90 days" (the year once when both ends share it).
    var period: String {
        let sameYear = calendar.component(.year, from: report.start) == calendar.component(.year, from: report.end)
        let startText = report.start.formatted(.dateTime.day().month(.wide).year(sameYear ? .omitted : .defaultDigits)
            .locale(locale))
        let endText = report.end.formatted(.dateTime.day().month(.wide).year().locale(locale))
        let days = report.dayCount == 1 ? "1 day" : "\(report.dayCount) days"
        return "\(startText) – \(endText) · \(days)"
    }

    var daysWithEntries: String { "\(report.daysWithEntries) of \(report.dayCount)" }

    /// "81%", or "—" with nothing to count.
    func percent(_ rate: Double?) -> String {
        rate.map { "\(Int(($0 * 100).rounded()))%" } ?? "—"
    }

    var longestStreak: String { report.longestStreak == 1 ? "1 day" : "\(report.longestStreak) days" }

    /// "At least 4,000 IU", "At most 400 mg", "Between 120–160 g".
    func goal(_ section: DoctorReport.Section) -> String {
        switch section.goalType {
        case .minimum: "At least \(amount(section.target, section.unit))"
        case .maximum: "At most \(amount(section.target, section.unit))"
        case .range:
            if let upper = section.upperBound {
                "Between \(number(section.target))–\(number(upper)) \(section.unit)"
            } else {
                "At least \(amount(section.target, section.unit))"
            }
        }
    }

    func average(_ section: DoctorReport.Section) -> String {
        section.average.map { amount($0, section.unit) } ?? "—"
    }

    /// "Generated by nutrx on 14 Oct 2026".
    func generated(on date: Date) -> String {
        "Generated by nutrx on \(date.formatted(.dateTime.day().month(.abbreviated).year().locale(locale)))"
    }

    static func pageNumber(_ page: Int, of count: Int) -> String { "page \(page) of \(count)" }

    /// "2 Aug".
    func noteDate(_ date: Date) -> String { date.formatted(.dateTime.day().month(.abbreviated).locale(locale)) }

    /// "nutrx-report-2026-07-16-to-2026-10-13.pdf".
    var fileName: String {
        let format = Date.ISO8601FormatStyle(timeZone: calendar.timeZone).year().month().day().dateSeparator(.dash)
        return "nutrx-report-\(report.start.formatted(format))-to-\(report.end.formatted(format)).pdf"
    }

    func amount(_ value: Double, _ unit: String) -> String { "\(number(value)) \(unit)" }

    func number(_ value: Double) -> String {
        value.formatted(.number.precision(.fractionLength(0...(value >= 100 ? 0 : 1))).locale(locale))
    }
}

/// How the report falls onto pages (nutrx Pro, phase 8): the cover with the summary table, then nutrient sections and
/// the notes packed onto content pages. `ImageRenderer` draws one view per page, so the split is decided here, from
/// fixed block heights in points (pure, `DoctorReportTests`).
struct ReportLayout: Equatable {
    enum Paper: Equatable {
        case a4, letter

        /// US Letter where it's the paper in use (the US, Canada, Mexico, the Philippines and a few others), A4 elsewhere.
        static func forRegion(_ region: String?) -> Paper {
            ["US", "CA", "MX", "PH", "CL", "CO", "VE", "GT", "PR"].contains(region ?? "") ? .letter : .a4
        }

        var size: CGSize { self == .a4 ? CGSize(width: 595, height: 842) : CGSize(width: 612, height: 792) }
    }

    enum Block: Equatable {
        case section(Int)
        case notesHeader
        /// Note rows, by index into `report.notes`.
        case notes(Range<Int>)
    }

    enum Page: Equatable {
        /// The cover, with these rows of the summary table.
        case cover(summaryRows: Range<Int>)
        /// The summary table continued, for a long list of nutrients.
        case summary(rows: Range<Int>)
        case content([Block])
    }

    let paper: Paper
    let pages: [Page]

    // Heights in points, for the page content between the header and the footer.
    static let margin: CGFloat = 54
    static let headerHeight: CGFloat = 40
    static let footerHeight: CGFloat = 56
    static let coverTopHeight: CGFloat = 330
    static let summaryHeaderHeight: CGFloat = 60
    static let summaryRowHeight: CGFloat = 28
    static let sectionHeight: CGFloat = 240
    static let trendLineHeight: CGFloat = 30
    static let notesHeaderHeight: CGFloat = 44
    static let noteRowHeight: CGFloat = 28

    static func contentHeight(_ paper: Paper) -> CGFloat {
        paper.size.height - 2 * margin - headerHeight - footerHeight
    }

    static func blockHeight(_ section: DoctorReport.Section) -> CGFloat {
        sectionHeight + CGFloat(section.trends.count) * trendLineHeight
    }

    init(report: DoctorReport, paper: Paper) {
        self.paper = paper
        let available = Self.contentHeight(paper)
        var pages: [Page] = []

        // Cover: as many summary rows as fit under the cover's top; the rest continue on summary pages.
        let rowCount = report.sections.count
        let coverRows = max(0, Int((available - Self.coverTopHeight - Self.summaryHeaderHeight) / Self.summaryRowHeight))
        pages.append(.cover(summaryRows: 0..<min(rowCount, coverRows)))
        var row = min(rowCount, coverRows)
        let rowsPerPage = max(1, Int((available - Self.summaryHeaderHeight) / Self.summaryRowHeight))
        while row < rowCount {
            let next = min(rowCount, row + rowsPerPage)
            pages.append(.summary(rows: row..<next))
            row = next
        }

        // Content: sections in order, then the notes, filling each page.
        var blocks: [Block] = []
        var used: CGFloat = 0
        func newPage() {
            if !blocks.isEmpty { pages.append(.content(blocks)) }
            blocks = []
            used = 0
        }
        for (index, section) in report.sections.enumerated() {
            let height = Self.blockHeight(section)
            if used + height > available { newPage() }
            blocks.append(.section(index))
            used += height
        }
        var note = 0
        if !report.notes.isEmpty {
            // The header needs room for at least one row below it.
            if used + Self.notesHeaderHeight + Self.noteRowHeight > available { newPage() }
            blocks.append(.notesHeader)
            used += Self.notesHeaderHeight
            while note < report.notes.count {
                let fit = Int((available - used) / Self.noteRowHeight)
                if fit <= 0 {
                    newPage()
                    continue
                }
                let next = min(report.notes.count, note + fit)
                blocks.append(.notes(note..<next))
                used += CGFloat(next - note) * Self.noteRowHeight
                note = next
            }
        }
        newPage()
        self.pages = pages
    }
}

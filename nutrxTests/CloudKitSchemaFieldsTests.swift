import CoreData
import SwiftData
import XCTest
@testable import nutrx

/// Keeps `Tools/CloudKitSchema/fields.txt`, the fields `Tools/check-cloudkit-schema` looks for in the production
/// schema before a TestFlight upload, in step with the models (#145). Core Data's CloudKit mirroring stores each
/// attribute and to-one relationship of entity `X` as field `CD_<name>` on record type `CD_X`; to-many relationships
/// aren't fields.
final class CloudKitSchemaFieldsTests: XCTestCase {
    private var fieldsFile: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("Tools/CloudKitSchema/fields.txt")
    }

    private func expectedFields() throws -> String {
        let model = try XCTUnwrap(NSManagedObjectModel.makeManagedObjectModel(for: ModelContainerFactory.models))
        var lines: [String] = []
        for entity in model.entities {
            let recordType = "CD_\(entity.name ?? "?")"
            for (name, property) in entity.propertiesByName {
                if let relationship = property as? NSRelationshipDescription, relationship.isToMany { continue }
                lines.append("\(recordType) CD_\(name)")
            }
        }
        let header = "# Generated by CloudKitSchemaFieldsTests from ModelContainerFactory.models. Don't edit by hand:\n"
            + "# run the test with TEST_RUNNER_UPDATE_CLOUDKIT_FIELDS=1 to rewrite it, then deploy any new field to\n"
            + "# production (CloudKit Console) before a TestFlight upload. Check with Tools/check-cloudkit-schema.\n"
        return header + lines.sorted().joined(separator: "\n") + "\n"
    }

    func testTheFieldListMatchesTheModels() throws {
        let expected = try expectedFields()
        if ProcessInfo.processInfo.environment["UPDATE_CLOUDKIT_FIELDS"] == "1" {
            try expected.write(to: fieldsFile, atomically: true, encoding: .utf8)
        }
        let committed = try String(contentsOf: fieldsFile, encoding: .utf8)
        XCTAssertEqual(committed, expected, """
            A model field changed. Run this test with TEST_RUNNER_UPDATE_CLOUDKIT_FIELDS=1 to update \
            Tools/CloudKitSchema/fields.txt, and deploy the new field to the production CloudKit schema before \
            a TestFlight upload.
            """)
    }

    func testItIncludesTheFieldsAddedIn2_2() throws {
        let expected = try expectedFields()
        for field in ["CD_Nutrient CD_endDate", "CD_Nutrient CD_courseGapsRaw", "CD_Nutrient CD_isRemoved",
                      "CD_LogStackEntry CD_nutrient"] {
            XCTAssertTrue(expected.contains(field + "\n"), field)
        }
        XCTAssertFalse(expected.contains("CD_Nutrient CD_intakeRecords"), "to-many relationships aren't fields")
    }
}
